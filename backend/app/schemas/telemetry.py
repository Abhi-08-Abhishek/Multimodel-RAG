from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class TokenUsage(BaseModel):
    """Token consumption and cost metrics for a single LLM invocation."""
    prompt_tokens: int = Field(default=0, description="Tokens in the prompt")
    completion_tokens: int = Field(default=0, description="Tokens generated by model")
    total_tokens: int = Field(default=0, description="Sum of prompt and completion tokens")
    estimated_cost_usd: float = Field(default=0.0, description="Cost calculated in USD via LiteLLM")
    latency_seconds: float = Field(default=0.0, description="Duration of model inference in seconds")
    model: str = Field(default="", description="Target model name used for completion")


class TelemetryTrace(BaseModel):
    """Detailed trace record for an individual LLM execution."""
    trace_id: str
    timestamp: str
    operation: str  # "rag_query" | "visual_summarization"
    model: str
    modality: str   # "text" | "visual"
    token_usage: TokenUsage
    status: str = "success"
    query_preview: Optional[str] = None


class TelemetrySummary(BaseModel):
    """Aggregated token, cost, and latency metrics across all invocations."""
    total_requests: int = 0
    total_prompt_tokens: int = 0
    total_completion_tokens: int = 0
    total_tokens: int = 0
    total_cost_usd: float = 0.0
    average_latency_seconds: float = 0.0
    model_breakdown: Dict[str, Dict[str, Any]] = Field(default_factory=dict)
